#!/usr/bin/env python3
"""manifest_lock.py — Echo's manifest lock and scope freeze (ROADMAP T-016; 1.0 bar rows 1-2; horde B428).

core/manifest.lock.json freezes what a release may never silently change:
  - every parameter's identity, in order: key, unit, type, morph class, rate class and stepped labels
    (params.json order is the state format's order and the C++ handle, so a reorder is a change too);
  - the fixed row (RS-5.8), in order: horde gives each fixed control a host parameter id by POSITION;
  - the actions (RS-4.12), by key and label;
  - the scope list, SPEC §1, by sha256 (bar row 1: "frozen at the feature freeze").
Ranges, defaults, names and laws are NOT locked here: check_manifest.py holds the C++ table to
spec/params.json for those, and they may still be tuned before release.

`module_version` is a hash of the locked KEY IDENTITY only (params, fixed row, actions), canonically
serialised: the first 16 hex digits of its sha256. It changes when a key does, never when the lock's note,
the renderer's layout or SPEC §1's wording does (ruled by poll 2026-10-24, D-041; contract §6.2: "so a load
can tell when a module's keys have changed"). `write` also generates core/include/echo/module_version.h, the
constant Echo ships, and `check` holds it to the lock.

  manifest_lock.py check                    the ./verify gate: params.json, SPEC §1 and module_version.h
                                            against the lock. First proves the detector on planted drifts.
  manifest_lock.py write --decision D-NNN   regenerate the lock and the header. A HUMAN GATE (D-041): it
                                            refuses unless D-NNN is a heading in DECISIONS.md, and records
                                            it in the lock. The lock and the header are protected paths
                                            (CLAUDE.md). After the first release, keys are append-only (B428).
  manifest_lock.py version                  print module_version.
"""
import copy
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOCK = ROOT / "core" / "manifest.lock.json"
PARAMS = ROOT / "spec" / "params.json"
SPEC = ROOT / "spec" / "SPEC.md"
HEADER = ROOT / "core" / "include" / "echo" / "module_version.h"
DECISIONS = ROOT / "DECISIONS.md"
IDENTITY = ("key", "unit", "type", "morph", "rate")


def scope_text(spec_md):
    """SPEC §1, from its heading up to (not including) §2's. A missing anchor raises: a mis-slice would make
    the pin vacuous (the same rule as the lab and plan-map smokes)."""
    a = spec_md.find("\n## 1. Scope list")
    b = spec_md.find("\n## 2. ", a + 1)
    if a < 0 or b < 0:
        raise SystemExit("manifest_lock: SPEC §1's anchors not found — the scope pin would be vacuous")
    return spec_md[a + 1:b]


def model(params_json, spec_md):
    """The locked view of the current sources."""
    p = json.loads(params_json)
    return {
        "params": [dict({f: x[f] for f in IDENTITY}, labels=x.get("labels", [])) for x in p["params"]],
        "fixedControls": [{"k": f["k"], "label": f["label"], "key": f["key"]} for f in p.get("fixedControls", [])],
        "actions": [{"key": a["key"], "label": a["label"]} for a in p.get("actions", [])],
        "scope_sha256": hashlib.sha256(scope_text(spec_md).encode()).hexdigest(),
    }


def version_of(m):
    """module_version: the key identity alone, canonically serialised (D-041)."""
    ident = {"params": m["params"], "fixedControls": m["fixedControls"], "actions": m["actions"]}
    return hashlib.sha256(json.dumps(ident, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()[:16]


def render(m, decision):
    """The lock file's text: one entry per line, so a diff names the entry that moved."""
    lines = ["{",
             ' "_note": "Echo manifest lock (T-016, B428). Generated by tools/manifest_lock.py write --decision; never edited by hand. '
             'A protected path: regenerating it is a human gate recorded in DECISIONS (D-041); after the first release keys are '
             'append-only. module_version hashes the key identity below.",',
             ' "lock": "echo-lock 1",',
             f' "decision": "{decision}",',
             f' "module_version": "{version_of(m)}",',
             f' "scope_sha256": "{m["scope_sha256"]}",',
             ' "params": [']
    lines += ["  " + json.dumps(x, ensure_ascii=False) + ("," if i + 1 < len(m["params"]) else "") for i, x in enumerate(m["params"])]
    lines += [" ],", ' "fixedControls": [']
    lines += ["  " + json.dumps(x, ensure_ascii=False) + ("," if i + 1 < len(m["fixedControls"]) else "") for i, x in enumerate(m["fixedControls"])]
    lines += [" ],", ' "actions": [']
    lines += ["  " + json.dumps(x, ensure_ascii=False) + ("," if i + 1 < len(m["actions"]) else "") for i, x in enumerate(m["actions"])]
    lines += [" ]", "}", ""]
    return "\n".join(lines)


def diff(lock, cur):
    """Every way the current sources leave the lock, as text."""
    out = []
    lk, ck = [x["key"] for x in lock["params"]], [x["key"] for x in cur["params"]]
    for k in lk:
        if k not in ck:
            out.append(f"key {k} is locked but gone (removed or renamed)")
    for k in ck:
        if k not in lk:
            out.append(f"key {k} is not in the lock (new or renamed): regenerate the lock deliberately")
    if [k for k in ck if k in lk] != [k for k in lk if k in ck]:
        out.append("the keys are reordered (the state format's order and the C++ handles)")
    byk = {x["key"]: x for x in lock["params"]}
    for x in cur["params"]:
        y = byk.get(x["key"])
        if y:
            for f in IDENTITY[1:] + ("labels",):
                if x.get(f) != y.get(f):
                    out.append(f"key {x['key']}: {f} {y.get(f)!r} -> {x.get(f)!r}")
    if cur["fixedControls"] != lock["fixedControls"]:
        out.append(f"the fixed row moved: {lock['fixedControls']} -> {cur['fixedControls']}")
    if cur["actions"] != lock["actions"]:
        out.append(f"the actions moved: {lock['actions']} -> {cur['actions']}")
    if cur["scope_sha256"] != lock["scope_sha256"]:
        out.append("SPEC §1 (the scope list) changed since the lock")
    return out


def render_header(version, decision):
    return (f"// echo/module_version.h — GENERATED by tools/manifest_lock.py write --decision {decision}; never edit.\n"
            "// Echo's module_version (rack-slot contract §6.2): a hash of the locked key identity in\n"
            "// core/manifest.lock.json (D-041). Every preset carries it, so a host can tell when Echo's keys\n"
            "// changed. ./verify's params_lock_gate holds this file to the lock. A protected path.\n"
            "#pragma once\n#include <string_view>\n\nnamespace echo {\n"
            f"inline constexpr std::string_view kModuleVersion = \"{version}\";\n}}  // namespace echo\n")


def header_version():
    m = re.search(r'kModuleVersion = "([0-9a-f]{16})"', HEADER.read_text()) if HEADER.exists() else None
    return m.group(1) if m else None


def module_version():
    return version_of(lock_model(json.loads(LOCK.read_text())))


def check():
    if not LOCK.exists():
        print(f"manifest_lock: {LOCK.relative_to(ROOT)} missing", file=sys.stderr)
        return 1
    lock = json.loads(LOCK.read_text())
    cur = model(PARAMS.read_text(), SPEC.read_text())
    if render(lock_model(lock), lock.get("decision", "")) != LOCK.read_text():
        print("manifest_lock: the lock file is not in its generated form (edited by hand?)", file=sys.stderr)
        return 1
    if lock.get("module_version") != version_of(lock_model(lock)):
        print("manifest_lock: the lock's module_version is not its keys' hash", file=sys.stderr)
        return 1
    if header_version() != lock["module_version"]:
        print(f"manifest_lock: core/include/echo/module_version.h says {header_version()}, the lock {lock['module_version']}",
              file=sys.stderr)
        return 1
    if not decision_exists(lock.get("decision", "")):
        print(f"manifest_lock: the lock cites {lock.get('decision')!r}, which is not a decision in DECISIONS.md", file=sys.stderr)
        return 1

    # The detector first sees its plants (T-016's three, and the rest of what it must catch).
    def planted(fn):
        c = copy.deepcopy(cur)
        fn(c)
        return c
    plants = [
        ("a renamed key", planted(lambda c: c["params"][2].__setitem__("key", "wet"))),
        ("a dropped label", planted(lambda c: c["params"][14]["labels"].pop())),
        ("two fixed controls swapped", planted(lambda c: c["fixedControls"].__setitem__(slice(0, 2), c["fixedControls"][1::-1]))),
        ("a re-classed key", planted(lambda c: c["params"][2].__setitem__("morph", "jump"))),
        ("an unlisted new key", planted(lambda c: c["params"].append(dict(c["params"][2], key="mix.width")))),
        ("a removed key", planted(lambda c: c["params"].pop())),
        ("a reordered pair", planted(lambda c: c["params"].__setitem__(slice(6, 8), c["params"][7:5:-1]))),
        ("a dropped action", planted(lambda c: c["actions"].clear())),
        ("an edited scope list", planted(lambda c: c.__setitem__("scope_sha256", "0" * 64))),
    ]
    # module_version must move when, and only when, the key identity does.
    base = version_of(cur)
    if version_of(plants[0][1]) == base or version_of(plants[2][1]) == base:
        print("manifest_lock: module_version did NOT move with a key change (vacuous)", file=sys.stderr)
        return 1
    if version_of(dict(cur, scope_sha256="0" * 64)) != base:
        print("manifest_lock: module_version moved with the scope prose alone", file=sys.stderr)
        return 1
    for what, p in plants:
        if not diff(lock, p):
            print(f"manifest_lock: the detector did NOT see {what} (vacuous)", file=sys.stderr)
            return 1

    problems = diff(lock, cur)
    for line in problems:
        print(f"manifest_lock: {line}", file=sys.stderr)
    if problems:
        print("manifest_lock: the manifest left its lock. This is a HUMAN GATE (D-041): only after the human rules the "
              "change and it is recorded in DECISIONS, `tools/manifest_lock.py write --decision D-NNN`.", file=sys.stderr)
        return 1
    print(f"manifest_lock: OK — {len(cur['params'])} keys, {len(cur['fixedControls'])} fixed controls, {len(cur['actions'])} action(s) "
          f"and SPEC §1 match the lock; {len(plants)} planted drifts seen; module_version {module_version()}")
    return 0


def lock_model(lock):
    return {k: lock[k] for k in ("params", "fixedControls", "actions", "scope_sha256")}


def decision_exists(d):
    return bool(re.fullmatch(r"D-\d{3}", d)) and re.search(rf"^## {d} ", DECISIONS.read_text(), re.M) is not None


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "check":
        return check()
    if cmd == "write":
        d = argv[3] if len(argv) > 3 and argv[2] == "--decision" else ""
        if not decision_exists(d):
            print("manifest_lock: write needs `--decision D-NNN`, a decision already in DECISIONS.md that rules this lock "
                  "change (a human gate, D-041). Refused; nothing written.", file=sys.stderr)
            return 1
        m = model(PARAMS.read_text(), SPEC.read_text())
        LOCK.write_text(render(m, d))
        HEADER.write_text(render_header(version_of(m), d))
        print(f"manifest_lock: wrote {LOCK.relative_to(ROOT)} and {HEADER.relative_to(ROOT)} under {d}; module_version {version_of(m)}")
        return 0
    if cmd == "version":
        print(module_version())
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
