// stereo_report.cpp — prints docs/stereo-report.md, the B408 stereo report
// (1.0 bar row 12; ROADMAP T-019; D-010 as ruled by D-044).
//
//   echo_stereo_report > docs/stereo-report.md
//
// ./verify regenerates it and fails if the committed file differs, so the report
// is always this build's readings. The metric, the law and the colouring flag
// are core/tests/fold.h, the same code echo_tests gates with (b408Gate,
// b408Controls, b408Zone): the report states, the suite judges. Exits non-zero
// if any gated generation breaks the law (or ping-pong's overlap leaves its
// closed form), so a red reading cannot be committed quietly either.
#include <cstdio>
#include <string>
#include <vector>

#include "fold.h"

namespace {

using echo::IrInput;
constexpr double kSr = 48000.0;

const char* kModes[] = {"stereo", "ping-pong", "mid/side"};
struct Stim {
  IrInput in;
  const char* name;
};
const Stim kStims[] = {{IrInput::Mono, "mono impulse"}, {IrInput::Noise, "seeded noise"}, {IrInput::SideOnly, "S-only impulse"}};

// Fixed-point text with no "-0": a reading that rounds to zero prints the same
// on every platform whatever the sign of its last ulp. Negatives take the true
// minus sign (U+2212), as "−∞" and the prose do (critic T-019 L4).
std::string num(double x, int prec) {
  if (std::isnan(x)) return "silent";
  if (std::isinf(x)) return x < 0 ? "−∞" : "∞";
  char b[64];
  std::snprintf(b, sizeof b, "%.*f", prec, x);
  std::string s = b;
  if (s[0] == '-') s = s.find_first_not_of("-0.") == std::string::npos ? s.substr(1) : "−" + s.substr(1);
  return s;
}
std::string dbOf(double rho) { return std::isnan(rho) ? "silent" : rho <= 0 ? "−∞" : num(fold::db(rho), 2); }
std::string hz(double f) { return f >= 1000 ? num(f / 1000, 2) + " kHz" : num(f, 0) + " Hz"; }
// The octave bands by their nominal names; the centres are 1000 * 2^k exactly.
const char* kBandNames[fold::kOctaves] = {"31.5", "63", "125", "250", "500", "1k", "2k", "4k", "8k", "16k"};

}  // namespace

int main() {
  int fails = 0;
  std::string o =
      "# Echo — B408 stereo report (mono-fold safety, 1.0 bar row 12)\n\n"
      "GENERATED by `echo_stereo_report > docs/stereo-report.md` (core/tools/stereo_report.cpp, T-019, D-044); never edit by hand.\n"
      "`./verify` fails if this file differs from a fresh run's. The readings are B408's \"measured and stated\".\n\n"
      "**The reading (D-010).** ρ = E_M / mean(E_L, E_R), with M = (L+R)/2 the mono fold: 1 (0 dB) for a centred source, ½ (−3 dB) for a\n"
      "hard-panned or decorrelated one, 0 for total cancellation; r = 2ρ − 1 is the correlation. Shown per repeat generation, per octave band\n"
      "(centres 31.25 Hz – 16 kHz) and as the ⅓-octave-smoothed worst notch with its frequency (a 1/24-octave grid): a broadband ratio cannot\n"
      "see a comb between time-separated taps.\n\n"
      "**How it is measured.** The wet alone (mix 100 %: the dry path is the input exactly, so the output's dry fold is the input's), through\n"
      "the one offline renderer `echo/ir_render.h` (D-011; it equals a plain `Echo` render bit for bit on every input here: `equalsPlainRender`\n"
      "in `echo_ir_tests`), at 48 kHz and −20 dBFS, rendered to the declared tail. Stimuli: the mono, left and right impulses; seeded\n"
      "decorrelated noise (mulberry32 seed 1, a burst of half the delay time); the S-only impulse (L = −R), which already folds to nothing\n"
      "at the input, so its rows read 0 *by construction* (Q-A4; ping-pong's mono encode removes it entirely).\n\n"
      "**The law (D-044), gated by `b408Gate` in `echo_tests`** on the equal-time patches, every generation, on the exact inputs only\n"
      "(mono: ρ_in = 1; left, right: ρ_in = ½): stereo and mid/side keep ρ_out ≥ ρ_in; ping-pong has no cross term, ρ = ½ exactly: it\n"
      "sums the input to mono and hard-pans every repeat by design. Where ping-pong's repeats DO overlap (sustained material), its fold at\n"
      "1 kHz must equal the closed form (1 + g)² / (2 (1 + g²)), so a side inverted cannot hide. **Noise is reported, never judged:** a\n"
      "finite burst's ρ moves under the loop's filtering with no fault present, by more than any independent-sample margin (re-ruled by\n"
      "poll after the critic found 15 of 80 seeds breaking 3/(2√N)); its notches are mostly the burst's own sampling structure — read them\n"
      "against ρ_in. Offset patches are reported, not gated: an L/R offset is a requested widening.\n\n"
      "**The colouring flag (SPEC §3.2, D-044):** raised in stereo mode exactly when 0 < |tL − tR| < 40 ms (whole microseconds). 40 ms is\n"
      "a warning convention (the precedence-effect range), not a boundary this metric shows: a stereo offset combs the fold at low\n"
      "frequency at any size (see the +50 ms rows). Ping-pong's taps never coincide and mid/side's fold is exactly the M line, so an\n"
      "offset combs neither.\n";

  std::string gens =
      "\n## Per repeat generation (the gated patches)\n\nρ of each repeat; ρ_in is the input's own fold. The impulse rows are judged (a row that breaks\n"
      "the law reads **FAIL**); the noise rows are reported only.\n\n"
      "| mode | patch | input | ρ_in | g1 | g2 | g3 | g4 | g5 | g6 | g7 | g8 | law |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n";
  std::string bands = "\n## Per octave band (ρ in dB; nominal centres, exactly 1000 · 2^k Hz)\n\n| mode | patch | input |";
  for (int k = 0; k < fold::kOctaves; ++k) bands += std::string(" ") + kBandNames[k] + " |";
  bands += "\n|---|---|---|";
  for (int k = 0; k < fold::kOctaves; ++k) bands += "---|";
  bands += "\n";
  std::string sum =
      "\n## Summary\n\n| mode | patch | tL / tR | zone | input | ρ | dB | r | worst ⅓-octave notch | gate |\n"
      "|---|---|---|---|---|---|---|---|---|---|\n";

  const auto ps = fold::reportPatches();
  for (int mode = 0; mode < 3; ++mode)
    for (std::size_t pi = 0; pi < ps.size(); ++pi) {
      auto p = ps[pi].p;
      p[fold::keyIndex("route.mode")] = mode;
      for (const auto& st : kStims) {
        const auto t = fold::take(p, st.in, kSr, -1);
        if (!t.ok) {
          std::fprintf(stderr, "stereo_report: the renderer refused %s / %s / %s\n", kModes[mode], ps[pi].name, st.name);
          return 1;
        }
        const double tL = t.info.times[0], tR = t.info.times[1];
        const bool zone = fold::colouringZone(mode, tL, tR);
        const auto e = fold::energy(t.L, t.R);
        const double r = fold::rho(e);
        const auto sp = fold::spectra(t.L, t.R, kSr, t.info.restAt > 0 ? static_cast<std::size_t>(t.info.restAt) : 0);
        const auto n = fold::worstNotch(sp);
        // The notch, said plainly where a number would mislead: a fold of nothing has
        // no notch, and a flat fold's "worst" point is just the grid's first.
        std::string notch;
        if (std::isnan(r)) notch = "silent";
        else if (r <= 0) notch = "none: folds to nothing";
        else if (std::fabs(fold::db(n.rho) - fold::db(r)) < 0.005) notch = "flat";
        else notch = dbOf(n.rho) + " dB at " + hz(n.hz);
        std::string gate = "reported";
        if (st.in == IrInput::SideOnly) gate = "ρ_in = 0: *by construction*";
        if (ps[pi].gated && st.in == IrInput::Mono) gate = "PASS";
        if (ps[pi].gated && st.in == IrInput::Noise) gate = "reported";
        // The per-generation rows: the exact impulses judged, the noise reported.
        if (ps[pi].gated && st.in != IrInput::SideOnly) {
          std::vector<IrInput> ins = {st.in};
          if (st.in == IrInput::Mono) ins = {IrInput::Mono, IrInput::Left, IrInput::Right};
          for (IrInput gi : ins) {
            const auto tg = gi == st.in ? t : fold::take(p, gi, kSr, -1);
            const double rg = fold::rho(fold::energy(tg.inL, tg.inR));
            const bool judged = gi != IrInput::Noise;
            const auto g = fold::generations(tg.L, tg.R, tL * kSr);
            bool all = !g.empty();
            std::string row = "| " + std::string(kModes[mode]) + " | " + ps[pi].name + " | " +
                              (gi == IrInput::Mono ? "mono impulse" : gi == IrInput::Left ? "left impulse" : gi == IrInput::Right ? "right impulse" : st.name) +
                              " | " + num(rg, 4) + " |";
            for (int k = 0; k < fold::kMaxGenerations; ++k) {
              if (k < static_cast<int>(g.size())) {
                const bool ok = !judged || fold::genPasses(mode, g[static_cast<std::size_t>(k)], rg);
                all = all && ok;
                row += " " + num(g[static_cast<std::size_t>(k)].rho, 4) + (ok ? "" : " **FAIL**") + " |";
              } else {
                row += " — |";
              }
            }
            row += std::string(" ") + (!judged ? "reported" : all ? (mode == fold::kPingPong ? "½, no cross term" : "≥ ρ_in") : "**FAIL**") + " |\n";
            gens += row;
            if (judged && !all) {
              ++fails;
              gate = "**FAIL**";
            }
          }
        }
        sum += "| " + std::string(kModes[mode]) + " | " + ps[pi].name + " | " + num(tL * 1000, 1) + " / " + num(tR * 1000, 1) + " ms | " +
               (zone ? "**in zone**" : "—") + " | " + st.name + " | " + num(r, 4) + " | " + dbOf(r) + " | " + num(fold::corr(e), 4) + " | " +
               notch + " | " + gate + " |\n";
        if (st.in != IrInput::SideOnly) {
          bands += "| " + std::string(kModes[mode]) + " | " + ps[pi].name + " | " + st.name + " |";
          for (double b : fold::octaves(sp)) bands += " " + dbOf(b) + " |";
          bands += "\n";
        }
      }
    }
  std::string legend = "\n## Patches\n\nEach in all three modes (`route.mode`), mix 100 %, the rest at the manifest defaults.\n\n| patch | what | gated |\n|---|---|---|\n";
  for (const auto& p : ps) legend += std::string("| ") + p.name + " | " + p.what + " | " + (p.gated ? "yes: equal times" : "no: reported") + " |\n";
  o += legend + sum + gens + bands;
  o += "\n## The metric's controls (prior-art §5.3's P1 – P5, restated in ρ's scale by D-044)\n\n"
       "Asserted by `b408Controls` in `echo_tests` (P3 against the closed-form ⅓-octave average of cos²(πfd)); each is a must-fail plant's\n"
       "witness (`foldScaleSlip`, `foldNotchUnsmoothed`, `foldOctaveNarrow`; P5′'s is `pingpongInvertsR`, in `b408Gate`).\n\n| control | expected | reads |\n|---|---|---|\n";
  {
    const long n = 1 << 16;
    fold::Vec L(static_cast<std::size_t>(n), 0.0), R = L;
    L[0] = 1, R[0] = -1;
    o += "| P1 hL = δ, hR = −δ | ρ = 0, total loss: the law FAILS | ρ = " + num(fold::rho(fold::energy(L, R)), 4) + " |\n";
    R[0] = 1;
    o += "| P2 hL = hR = δ | ρ = 1: PASS | ρ = " + num(fold::rho(fold::energy(L, R)), 4) + " |\n";
    R[0] = 0, R[48] = 1;  // 1 ms at 48 kHz
    const auto nn = fold::worstNotch(fold::spectra(L, R, kSr));
    o += "| P3 a 1 ms equal-gain offset | ρ = ½ broadband (no cross term); the notch view finds ~500 Hz | ρ = " + num(fold::rho(fold::energy(L, R)), 4) +
         "; worst notch " + dbOf(nn.rho) + " dB at " + hz(nn.hz) + " |\n";
    auto p = fold::patchWith({{"route.mode", fold::kMidSide}});
    const auto s = fold::take(p, IrInput::SideOnly, kSr, -1);
    o += "| P4 S-only repeats in mid/side | ρ = 0, *by construction* | ρ = " + num(fold::rho(fold::energy(s.L, s.R)), 4) + " |\n";
    p = fold::patchWith({{"route.mode", fold::kPingPong}});
    const auto q = fold::take(p, IrInput::Mono, kSr, -1);
    std::string per;
    for (const auto& g : fold::generations(q.L, q.R, q.info.times[0] * kSr)) per += (per.empty() ? "" : ", ") + num(g.rho, 4);
    o += "| P5 equal-time ping-pong, mono input | ρ = ½ (−3 dB) every repeat, no cross term | " + per + " |\n";
    const auto v = fold::take(fold::patchWith({{"route.mode", fold::kPingPong}, {"filt.loop.on", 0}}), IrInput::Mono, kSr, -1);
    const double got = fold::foldAt(v.L, v.R, 1000.0, kSr), want = fold::pingPongFoldClosedForm(0.35);
    if (!(std::fabs(got - want) < 1e-3)) ++fails;
    o += "| P5′ ping-pong where repeats overlap (sustained 1 kHz, loop filter off, 35 %) | (1 + g)² / (2 (1 + g²)) = " + num(want, 4) +
         "; a side inverted would read " + num((1 - 0.35) * (1 - 0.35) / (2 * (1 + 0.35 * 0.35)), 4) + " | " + num(got, 4) + " |\n";
  }
  std::fwrite(o.data(), 1, o.size(), stdout);
  if (fails) std::fprintf(stderr, "stereo_report: %d gated row(s) break the law (D-044)\n", fails);
  return fails ? 1 : 0;
}
