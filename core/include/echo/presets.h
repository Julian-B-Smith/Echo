// echo/presets.h — Echo's module presets (SPEC §16.3; M3 T-017, rewritten by T-039 under
// D-050; horde SPEC-MODULE-MACROS §4; contract rows A12, A13). C++ is the ONE source
// (ruled by poll 2026-10-24, D-042): `echo_presets --json` writes
// presets/echo-factory.json from factory(), and ./verify fails if the file drifts.
//
// THE MODEL. A ModulePreset is an id, a label, a description and the value of EVERY
// patch key (internal_defaults, by name in the file; Device keys never appear, RS-4.5).
// The bank is plain values.
//
// WHY THERE ARE NO MACROS (D-050). Echo is one of the simpler modules; macros are for
// modules with deep internals (RS-5.1: a module "may" offer them, and factory presets
// stay required). The file keeps `slots: []` on every preset: SPEC-MODULE-MACROS §4
// draws `slots` as a map (with `module` per preset, where the file has one at its top),
// no reader of horde's is in our record, so whether horde needs the field, or accepts
// this file as it is, is unknown and asked in echo-004 (D-050 A1). readBank REFUSES a
// preset whose slots are not empty, naming the preset. `macroLaw` is gone with them:
// the packet marks it optional, absent = `set` (SPEC-MODULE-MACROS §4), and with no
// slots it means nothing. The reader refuses it as an unknown field.
//
// VALIDATION refuses: an empty id or label; a control character in a string; a
// Device key in a preset; an unknown key; a missing key; a value out of range.
// Main thread only: this file allocates (strings, vectors).
